#ifndef ZEPHYR_INCLUDE_DT_BINDINGS_PINCTRL_LPC8N04_PINCTRL_H_
#define ZEPHYR_INCLUDE_DT_BINDINGS_PINCTRL_LPC8N04_PINCTRL_H_

/**
 * @file
 * @brief NXP LPC8N04 pin functions (UM11074, chapter 20).
 *
 * Encoding read by the LPC IOCON pinctrl driver: IOCON register index in
 * bits [31:20], pad type in bits [19:18], IOCON register value in the low
 * bits.
 */

/** @cond INTERNAL_HIDDEN */

#define LPC8N04_IOCON_TYPE_D 0x0
#define LPC8N04_IOCON_TYPE_I 0x1

#define LPC8N04_IOCON_MUX(pin, type, func) (((pin) << 20) | ((type) << 18) | (func))

/* PIO0_4/PIO0_5 as GPIO: I2CMODE = 01b, open-drain GPIO pad mode. */
#define LPC8N04_IOCON_I2CMODE_GPIO (1 << 8)

/** @endcond */

#define PIO0_0_PIO0_0    LPC8N04_IOCON_MUX(0, LPC8N04_IOCON_TYPE_D, 0)
#define PIO0_0_WAKEUP    LPC8N04_IOCON_MUX(0, LPC8N04_IOCON_TYPE_D, 1)
#define PIO0_1_PIO0_1    LPC8N04_IOCON_MUX(1, LPC8N04_IOCON_TYPE_D, 0)
#define PIO0_1_CLKOUT    LPC8N04_IOCON_MUX(1, LPC8N04_IOCON_TYPE_D, 1)
#define PIO0_2_PIO0_2    LPC8N04_IOCON_MUX(2, LPC8N04_IOCON_TYPE_D, 0)
#define PIO0_2_SSP_SSEL  LPC8N04_IOCON_MUX(2, LPC8N04_IOCON_TYPE_D, 1)
#define PIO0_3_PIO0_3    LPC8N04_IOCON_MUX(3, LPC8N04_IOCON_TYPE_D, 0)
#define PIO0_3_CT16B_M0  LPC8N04_IOCON_MUX(3, LPC8N04_IOCON_TYPE_D, 1)
#define PIO0_4_PIO0_4    LPC8N04_IOCON_MUX(4, LPC8N04_IOCON_TYPE_I, LPC8N04_IOCON_I2CMODE_GPIO)
#define PIO0_4_I2C_SCL   LPC8N04_IOCON_MUX(4, LPC8N04_IOCON_TYPE_I, 1)
#define PIO0_5_PIO0_5    LPC8N04_IOCON_MUX(5, LPC8N04_IOCON_TYPE_I, LPC8N04_IOCON_I2CMODE_GPIO)
#define PIO0_5_I2C_SDA   LPC8N04_IOCON_MUX(5, LPC8N04_IOCON_TYPE_I, 1)
#define PIO0_6_PIO0_6    LPC8N04_IOCON_MUX(6, LPC8N04_IOCON_TYPE_D, 0)
#define PIO0_6_SSP_SCLK  LPC8N04_IOCON_MUX(6, LPC8N04_IOCON_TYPE_D, 1)
#define PIO0_7_PIO0_7    LPC8N04_IOCON_MUX(7, LPC8N04_IOCON_TYPE_D, 0)
#define PIO0_7_CT16B_M1  LPC8N04_IOCON_MUX(7, LPC8N04_IOCON_TYPE_D, 1)
#define PIO0_8_PIO0_8    LPC8N04_IOCON_MUX(8, LPC8N04_IOCON_TYPE_D, 0)
#define PIO0_8_SSP_MISO  LPC8N04_IOCON_MUX(8, LPC8N04_IOCON_TYPE_D, 1)
#define PIO0_9_PIO0_9    LPC8N04_IOCON_MUX(9, LPC8N04_IOCON_TYPE_D, 0)
#define PIO0_9_SSP_MOSI  LPC8N04_IOCON_MUX(9, LPC8N04_IOCON_TYPE_D, 1)
#define PIO0_10_PIO0_10  LPC8N04_IOCON_MUX(10, LPC8N04_IOCON_TYPE_D, 0)
#define PIO0_10_CT32B_M0 LPC8N04_IOCON_MUX(10, LPC8N04_IOCON_TYPE_D, 1)
#define PIO0_10_SWCLK    LPC8N04_IOCON_MUX(10, LPC8N04_IOCON_TYPE_D, 2)
#define PIO0_11_PIO0_11  LPC8N04_IOCON_MUX(11, LPC8N04_IOCON_TYPE_D, 0)
#define PIO0_11_CT32B_M1 LPC8N04_IOCON_MUX(11, LPC8N04_IOCON_TYPE_D, 1)
#define PIO0_11_SWDIO    LPC8N04_IOCON_MUX(11, LPC8N04_IOCON_TYPE_D, 2)

#endif /* ZEPHYR_INCLUDE_DT_BINDINGS_PINCTRL_LPC8N04_PINCTRL_H_ */
